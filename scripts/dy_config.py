"""Single source of truth for machine-specific configuration.

Everything that used to be a hard-coded ``D:/...`` path lives here now.  You
normally do NOT edit this file: set the environment variables documented in
``.env.example`` instead.

Defaults work on a fresh clone on Windows, macOS and Linux without assuming a
D: drive exists.  Run ``python scripts/doctor.py`` to see the effective values.
"""
from __future__ import annotations

import os
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPTS_DIR = Path(__file__).resolve().parent
# When cloned into ~/.workbuddy/skills/, REPO_ROOT *is* the skill directory.
SKILL_DIR = REPO_ROOT


def _default_root() -> Path:
    """Windows with a D: drive keeps the original layout; everything else uses $HOME."""
    if os.name == "nt" and Path("D:/").exists():
        return Path("D:/douyin-distill")
    return Path.home() / "douyin-distill"


def _env_path(name: str, default: Path) -> Path:
    """An empty variable means 'use the default', never '' -> current directory."""
    raw = os.environ.get(name, "").strip()
    return Path(raw).expanduser() if raw else default


# Product root: downloaded media, run dirs, notes, receipts.
DISTILL_ROOT = _env_path("DOUYIN_DISTILL_ROOT", _default_root())

# Discovery-layer queue state (watch.py / run_batch.py / daily_brief.py).
WATCH_ROOT = _env_path("DOUYIN_WATCH_ROOT", DISTILL_ROOT / "_watch")

# Offline ASR install root (ffmpeg + sherpa-onnx SenseVoice + silero VAD).
ASR_ROOT = _env_path("WORKBUDDY_ASR_ROOT", DISTILL_ROOT / "asr")

# Optional vendored search engine (zhubaohe123/Douyin-api), NOT shipped here.
VENDOR_DIR = _env_path("DOUYIN_VENDOR_DIR", DISTILL_ROOT / "_vendor" / "douyin-api")

# ima knowledge base that receives the distilled notes. Required for stage 4/5.
IMA_KB_ID = os.environ.get("IMA_KB_ID", "").strip()


def require_kb_id() -> str:
    """Fail with an actionable message instead of uploading to a placeholder."""
    if not IMA_KB_ID:
        raise SystemExit(
            "IMA_KB_ID 未设置：请把它指向你自己的 ima 独立知识库 ID。\n"
            "参见 .env.example，或运行 python scripts/doctor.py 查看当前配置。"
        )
    return IMA_KB_ID


def summary() -> dict[str, str]:
    """Effective configuration, for doctor.py and for debugging."""
    return {
        "DOUYIN_DISTILL_ROOT": str(DISTILL_ROOT),
        "DOUYIN_WATCH_ROOT": str(WATCH_ROOT),
        "WORKBUDDY_ASR_ROOT": str(ASR_ROOT),
        "DOUYIN_VENDOR_DIR": str(VENDOR_DIR),
        "IMA_KB_ID": IMA_KB_ID or "(未设置)",
        "SKILL_DIR": str(SKILL_DIR),
    }


if __name__ == "__main__":
    for _key, _value in summary().items():
        print(f"{_key:24} {_value}")
